"""The achievements' icons (docs/achievements.md) from assets/achievements/: one atlas of them all, as straight RGBA bytes in a C
header written by nx2/build.py into the build's own folder, as nx2/logo_rgba.py does for the logo (gpu/vk/vk_imgui.cpp loads it,
vk_menu.cpp draws from it). One texture, not one an icon: the overlays' backend has a small pool of textures, and a texture it
cannot make holds back every overlay (vk_imgui.cpp record_to).

For an id of gpu/vk/oot_achievements.h, <id>.png is the unlocked icon and <id>_locked.png the locked one; either may be missing
(the menu then draws its own medal, or the unlocked icon darkened). A PNG whose name is no id's stops the build, so a misspelled
file is never left out without a word; so does one larger than 256 x 256. scripts/make_achievement_icons.py draws the default set.

    python nx2/achievement_icons.py [out.h]

Standard library only (the PNG decoder is nx2/logo_rgba.py's: 8-bit RGBA or RGB, not interlaced).
"""
import os
import re
import sys

import logo_rgba

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FOLDER = os.path.join(ROOT, "assets", "achievements")
HEADER = os.path.join(ROOT, "gpu", "vk", "oot_achievements.h")
MAX_SIDE = 256
COLUMNS = 8   # (the atlas's cells to a row)


def ids(header=HEADER):
    with open(header, encoding="utf-8") as f:
        return re.findall(r'^\s*X\("([a-z0-9_]+)"', f.read(), re.M)


def icons(folder=FOLDER, header=HEADER):
    """[(id, locked, w, h, rgba)] in the list's order, the unlocked one first; raises ValueError for a stray or oversized PNG"""
    known = ids(header)
    files = sorted(f for f in os.listdir(folder) if f.lower().endswith(".png")) if os.path.isdir(folder) else []
    found = {}
    for name in files:
        stem = name[:-4]
        locked = stem.endswith("_locked")
        id_ = stem[:-7] if locked else stem
        if id_ not in known:
            raise ValueError("assets/achievements/%s: no achievement has the id %r (gpu/vk/oot_achievements.h)" % (name, id_))
        with open(os.path.join(folder, name), "rb") as f:
            w, h, px = logo_rgba.decode(f.read())
        if w > MAX_SIDE or h > MAX_SIDE:
            raise ValueError("assets/achievements/%s: %d x %d, larger than %d x %d" % (name, w, h, MAX_SIDE, MAX_SIDE))
        found[(id_, locked)] = (w, h, px)
    return [(i, locked) + found[(i, locked)] for i in known for locked in (False, True) if (i, locked) in found]


def atlas(got):
    """(width, height, rgba, [(id, locked, x, y, w, h)]): every icon in a cell of the largest one's size, COLUMNS to a row"""
    cell = max(max(w, h) for _, _, w, h, _ in got)
    cols = min(COLUMNS, len(got))
    rows = (len(got) + cols - 1) // cols
    aw, ah = cols * cell, rows * cell
    out = bytearray(aw * ah * 4)
    places = []
    for n, (id_, locked, w, h, px) in enumerate(got):
        x, y = n % cols * cell, n // cols * cell
        for row in range(h):
            out[((y + row) * aw + x) * 4:((y + row) * aw + x + w) * 4] = px[row * w * 4:(row + 1) * w * 4]
        places.append((id_, locked, x, y, w, h))
    return aw, ah, bytes(out), places


def header(folder=FOLDER, src=HEADER):
    got = icons(folder, src)
    lines = ["// generated by nx2/achievement_icons.py from assets/achievements/: do not edit", "#pragma once"]
    if not got:   # (no icons: the menu draws its own medals)
        return "\n".join(lines) + "\n"
    aw, ah, px, places = atlas(got)
    lines.append("#define LONGSHOT_ACHIEVEMENT_ICONS %d" % len(places))
    lines.append("static const unsigned longshot_achievement_atlas_w = %d, longshot_achievement_atlas_h = %d;" % (aw, ah))
    lines.append("static const unsigned char longshot_achievement_atlas_rgba[%d] = {" % len(px))
    for i in range(0, len(px), 32):
        lines.append(",".join(str(b) for b in px[i:i + 32]) + ",")
    lines.append("};")
    lines.append("struct LongshotAchievementIcon { const char* id; int locked; unsigned x, y, w, h; };")
    lines.append("static const LongshotAchievementIcon longshot_achievement_icons[%d] = {" % len(places))
    for id_, locked, x, y, w, h in places:
        lines.append('    {"%s", %d, %d, %d, %d, %d},' % (id_, int(locked), x, y, w, h))
    lines.append("};")
    return "\n".join(lines) + "\n"


def write(out_path, folder=FOLDER, src=HEADER):
    """Writes the header when it differs (an unchanged one keeps its timestamp); returns its text"""
    text = header(folder, src)
    try:
        with open(out_path, encoding="utf-8") as f:
            if f.read() == text:
                return text
    except OSError:
        pass
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return text


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "longshot_achievement_icons.h"
    write(out)
    print("achievement_icons: %s" % out)
